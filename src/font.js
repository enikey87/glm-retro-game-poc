export const FONT_CHARS = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:;!?' + "'-+×·/()<>=%"
const CHARS_PER_ROW = 11
const CELL = 16 // 5px glyph × 3 scale + 1px pad

export function buildRetroFont(scene, key = 'pfont', color = '#ffffff') {
  const glyphs = [...FONT_CHARS]
  const rows = Math.ceil(glyphs.length / CHARS_PER_ROW)
  const w = CHARS_PER_ROW * CELL
  const h = rows * CELL
  const canvas = scene.textures.createCanvas(key + '-img', w, h)
  const ctx = canvas.getContext()
  ctx.clearRect(0, 0, w, h)
  ctx.fillStyle = color
  glyphs.forEach((ch, i) => {
    const pat = G[ch]
    if (!pat) return
    const cx = (i % CHARS_PER_ROW) * CELL
    const cy = Math.floor(i / CHARS_PER_ROW) * CELL
    for (let y = 0; y < 5; y++) {
      for (let x = 0; x < 5; x++) {
        if (pat[y][x] === '#') ctx.fillRect(cx + x * 3, cy + y * 3, 3, 3)
      }
    }
  })
  canvas.refresh()
  const entry = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: key + '-img',
    width: CELL,
    height: CELL,
    chars: FONT_CHARS,
    charsPerRow: CHARS_PER_ROW,
    lineSpacing: 8,
  })
  if (scene.cache.bitmapFont.exists(key)) scene.cache.bitmapFont.remove(key)
  scene.cache.bitmapFont.add(key, entry)
  return key
}
